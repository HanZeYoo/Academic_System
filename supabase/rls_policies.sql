-- 4. USERS TABLE POLICIES
-- ------------------------------------------------------------------------------
DROP POLICY IF EXISTS "Users can view own profile or teachers/admins view all" ON public.users;
DROP POLICY IF EXISTS "Admins and teachers can insert users" ON public.users;
DROP POLICY IF EXISTS "Users can update own details, admins update all" ON public.users;
DROP POLICY IF EXISTS "Only admins can delete users" ON public.users;

-- SELECT: Users see their own account; Teachers & Admins see user list for lookups/FCM
CREATE POLICY "Users can view own profile or teachers/admins view all" ON public.users
FOR SELECT TO authenticated
USING (
  username = (auth.jwt() ->> 'email') 
  OR public.is_teacher()
);

-- INSERT: Teachers and Admins can create user accounts (student, parent, teacher)
CREATE POLICY "Admins and teachers can insert users" ON public.users
FOR INSERT TO authenticated
WITH CHECK (
  public.is_teacher() 
  OR username = (auth.jwt() ->> 'email')
);

-- UPDATE: Users can update their own password/FCM token; Admins can update any
CREATE POLICY "Users can update own details, admins update all" ON public.users
FOR UPDATE TO authenticated
USING (
  username = (auth.jwt() ->> 'email') 
  OR public.is_admin()
)
WITH CHECK (
  -- Prevent non-admins from promoting themselves to 'admin' role
  (public.is_admin()) 
  OR (username = (auth.jwt() ->> 'email') AND role = (SELECT u.role FROM public.users u WHERE u.username = (auth.jwt() ->> 'email')))
);

-- DELETE: Only admins can delete user records
CREATE POLICY "Only admins can delete users" ON public.users
FOR DELETE TO authenticated
USING (public.is_admin());


