-- ------------------------------------------------------------------------------
-- 2. HELPER SECURITY FUNCTIONS (SECURITY DEFINER)
-- ------------------------------------------------------------------------------

-- Safely get current user's authenticated email from JWT
CREATE OR REPLACE FUNCTION public.current_user_email()
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT COALESCE(auth.jwt() ->> 'email', '');
$$;

-- Safely get current user's assigned role from public.users table
CREATE OR REPLACE FUNCTION public.current_user_role()
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT role FROM public.users 
  WHERE username = (auth.jwt() ->> 'email') 
  LIMIT 1;
$$;

-- Check if current user is an Admin
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.users 
    WHERE username = (auth.jwt() ->> 'email') 
      AND role IN ('admin', 'superadmin', 'principal', 'registrar')
  );
$$;

-- Check if current user is a Teacher or Admin
CREATE OR REPLACE FUNCTION public.is_teacher()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.users 
    WHERE username = (auth.jwt() ->> 'email') 
      AND role IN ('teacher', 'admin', 'superadmin', 'principal', 'registrar')
  );
$$;

-- Grant execution to authenticated users
GRANT EXECUTE ON FUNCTION public.current_user_email() TO authenticated;
GRANT EXECUTE ON FUNCTION public.current_user_role() TO authenticated;
GRANT EXECUTE ON FUNCTION public.is_admin() TO authenticated;
GRANT EXECUTE ON FUNCTION public.is_teacher() TO authenticated;


